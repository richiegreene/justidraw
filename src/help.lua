return [[
shortcuts
 B: freehand draw (Brush)
 P: line tool (Pen)
 E: eraser
 O: pan/zoom
 G: grab
 M: move
 C: comment
 S: smooth
 F: flatten (ctrl/cmd+shift+F: max flatten)
 H: dodge/burn envelope
 < and >: selected envelope
 ?: normalize envelope
 N: envelope tool
 T: transpose/stretch
 1-4+up/down: cent-octave shift
 U: smudge / vibrato
 R: Rectangular selection
 L: Lasso selection
 D: Deselect
 shift+N: toggle selecting notes or vertices
 shift+D: duplicate selection
 J: Join notes
 ctrl/cmd+A: select all visible notes (muted/locked parts omitted)
 ctrl/cmd+D: divide -- 16 (sixteenths), b.2, 32 (beat 2 only), b.2, 5:4
   add loudness/shape in brackets: 32 (+6dB; 0158) or 32 (5-15dB; 0158)
 ctrl/cmd+I: intensity over the highlight -- +6dB, -3, or 5-15dB to ramp
 V: thin selection (fewer vertices, same sound)
 shift+V: densify selection (silent, undoes thinning)
 ctrl+V: max segment length (thin further)
 ctrl+alt(⌥)+1-32: assign part color (0: clear; type two digits quickly)
 ctrl/cmd+alt(⌥)+R: assign selected notes by average register, lowest to highest -> 1..32
 shift+alt(⌥)+P: tell which part(s) the selection is registered as
 shift+ctrl+alt(⌥)+1-32: select part (0: unassigned; type two digits quickly)
 alt(⌥)+1-32: mute + lock part (0: unassigned; type two digits quickly)
 Y: Show harmonic series
 [ and ]: change brush radius
 + and -: change tempo
 Space: play/pause
 ctrl+P: snap to (*:octave repeating on/off)
 ctrl+Y / ctrl+shift+Z: redo
 ctrl+S: save
 ctrl+O: open save folder
 ctrl+R: render wav
 ctrl+T: cycle between themes
 ctrl+G: engrave's barlines / the plain grid
 ctrl+B: cycle between synths
 shift+ctrl/cmd+B: show/hide part colors
 shift+ctrl/cmd+P: name the assigned part under the cursor (Category / Name)
 Engrave part groups appear in the upper-right legend
 shift+R: reverb off/on
 Escape: quit
]]
